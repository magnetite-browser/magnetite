#!/usr/bin/env python3
"""Regenerate the dependency inventory and licence texts in THIRD_PARTY_NOTICES.md.

    python3 tools/third-party-notices.py          # rewrite the generated section
    python3 tools/third-party-notices.py --check  # exit 1 if it is out of date

Needs cargo, and pnpm with `pnpm install` done in crates/ui/web.

"Shipped" means the code ends up in something we distribute. For Rust, that is
the normal dependencies (not build, dev or proc-macro) of magnetite on the
macOS, Windows and Linux targets in TARGETS. For npm, it is the
sidebar's production packages, plus the build tools whose output lands in the
bundle. Everything else runs only at build or test time and is not listed.

Packages are named without versions, so routine updates (Dependabot's) leave
the section as it is; it changes when a shipped package, licence or copyright
line does. Which licences are allowed is `cargo deny`'s job (deny.toml).

The generated section ends with the licence texts of everything shipped, read
from each package's own licence files. Packages with the same text share one
copy, with all their copyright lines above it. A crate offered under several
licences, one of them MIT, is used under MIT and only its MIT file is copied.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
WEB = ROOT / "crates/ui/web"
BEGIN = "<!-- BEGIN GENERATED by tools/third-party-notices.py -->"
END = "<!-- END GENERATED -->"

# Targets we publish builds for.
TARGETS = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "x86_64-pc-windows-msvc",
    "aarch64-pc-windows-msvc",
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
]
# Shipped Rust binaries and the `cargo tree --target` values they are built for.
BINARIES = {"magnetite": TARGETS}
# npm dev dependencies whose output is part of the built sidebar bundle.
NPM_BUILD_OUTPUT = {"tailwindcss": "generated CSS", "vite": "module preload polyfill"}

LICENCE_FILE = re.compile(r"^(licen[cs]e|copying|unlicense)", re.I)
# A copyright line ("Copyright (c) 2019 Jane", "© Unicode"), not licence prose that
# wraps onto a new line ("copyright license to ...", "(c) You must retain ...").
COPYRIGHT = re.compile(
    r"^[\s/#*]*(?:(?:Copyright|COPYRIGHT)\s+(?!AND\b|NOTICE\b|HOLDERS?\b|OWNER\b)(?:\([cC]\)|©|\d|[A-Z])"
    r"|\([cC]\)\s*\d|©)"
)
# A symlink published as a plain file: it holds only its target's path.
LINK = re.compile(r"^\S+$")
# Vite's LICENSE.md appends the licences of its own bundled tooling; none of that
# code reaches our bundle, only Vite's own polyfill does.
BUNDLED_TAIL = "\n# Licenses of bundled dependencies"

MIT_TEXT = """\
Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE."""
CC0_TEXT = """\
Dedicated to the public domain under CC0 1.0 Universal
(https://creativecommons.org/publicdomain/zero/1.0/legalcode). No notice is required."""
CEF_RS = ("Copyright (c) 2023 Wu Yuwei", MIT_TEXT)  # tauri-apps/cef-rs, LICENSE-MIT
OBJC2 = ("Copyright 2026 Mads Marquart", MIT_TEXT)  # madsmtm/objc2, LICENSE-MIT.txt
# Shipped crates published without a licence file: (copyright line, text) taken
# from their repositories. A new crate without a file stops the script.
NO_LICENCE_FILE = {
    "cef": CEF_RS,
    "cef-dll-sys": CEF_RS,
    "block2": OBJC2,
    "objc2": OBJC2,
    "objc2-app-kit": OBJC2,
    "objc2-core-foundation": OBJC2,
    "objc2-core-graphics": OBJC2,
    "objc2-encode": OBJC2,
    "objc2-foundation": OBJC2,
    "bitcoin_hashes": ("", CC0_TEXT),
    # redox-os/seahash, LICENSE: the MIT text without a copyright line.
    "seahash": ("", MIT_TEXT),
    # google/flatbuffers, LICENSE (Apache-2.0); the copyright from its sources.
    "flatbuffers": (
        "Copyright 2018 Google Inc. All rights reserved.",
        (Path(__file__).parent / "licences" / "flatbuffers-LICENSE").read_text().strip(),
    ),
}
# Opening words of common licence texts, only to title the groups of texts.
KNOWN_TEXTS = {
    "Apache-2.0": "Apache License",
    "BSD-3-Clause": "Neither the name",
    "BSL-1.0": "Boost Software License",
    "CC0-1.0": "CC0 1.0 Universal",
    "CDLA-Permissive-2.0": "Community Data License Agreement",
    "ISC": "Permission to use, copy, modify, and/or distribute",
    "MIT": "to deal in the Software without restriction",
    "Unicode-3.0": "UNICODE LICENSE V3",
    "Zlib": "This software is provided 'as-is'",
}

OUR_REPOSITORIES = "https://github.com/magnetite-browser/"

Key = tuple[str, str]  # (name, version)
Package = tuple[str, Path]  # (licence expression, directory with its files)


def run(*cmd: str, cwd: Path = ROOT) -> str:
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True).stdout


def rust_crates() -> dict[Key, Package]:
    """Licence and source directory of every third-party crate in Cargo.lock."""
    meta = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked"))
    ours = set(meta["workspace_members"])
    return {
        (p["name"], p["version"]): (p["license"] or "UNKNOWN", Path(p["manifest_path"]).parent)
        for p in meta["packages"]
        # Our crates from other repositories (the sync protocol) are ours too.
        if p["id"] not in ours and not (p.get("repository") or "").startswith(OUR_REPOSITORIES)
    }


def shipped_crates(binary: str, targets: list[str]) -> set[Key]:
    cmd = ["cargo", "tree", "--locked", "-p", binary, "-e", "normal,no-proc-macro"]
    cmd += ["--prefix", "none", "-f", "{p}"]
    for target in targets:
        cmd += ["--target", target]
    keys = set()
    for line in filter(None, run(*cmd).splitlines()):
        name, version = line.split()[:2]
        keys.add((name, version.removeprefix("v")))
    return keys


def npm_packages(prod: bool) -> dict[Key, Package]:
    cmd = ["pnpm", "licenses", "list", "--json"] + (["--prod"] if prod else [])
    by_licence = json.loads(run(*cmd, cwd=WEB))
    return {
        (pkg["name"], version): (licence, Path(path))
        for licence, pkgs in by_licence.items()
        for pkg in pkgs
        for version, path in zip(pkg["versions"], pkg["paths"])
    }


def licence_files(key: Key, package: Package) -> list[tuple[str, str]]:
    """(copyright lines, licence text) of one package, from its own files."""
    licence, folder = package
    files = sorted(f for f in folder.iterdir() if f.is_file() and LICENCE_FILE.match(f.name))
    if " AND " not in licence and "MIT" in licence:
        files = [f for f in files if "MIT" in f.name.upper()] or files
    if not files:
        if key[0] not in NO_LICENCE_FILE:
            sys.exit(f"{key[0]} {key[1]} ships no licence file: add it to NO_LICENCE_FILE")
        return [NO_LICENCE_FILE[key[0]]]
    texts = []
    for file in files:
        content = file.read_text(errors="replace").split(BUNDLED_TAIL)[0].strip()
        if LINK.match(content):
            sys.exit(f"{key[0]} {key[1]}: {file.name} only links to {content}: take the text from where it points")
        lines = content.splitlines()
        copyright = "\n".join(line.strip() for line in lines if COPYRIGHT.match(line))
        texts.append((copyright, "\n".join(line for line in lines if not COPYRIGHT.match(line)).strip()))
    return texts


def render_texts(packages: dict[Key, Package]) -> list[str]:
    # Grouped by the text with whitespace normalised: (text, copyright lines, users).
    groups: dict[str, tuple[str, set[str], set[str]]] = {}
    for key in sorted(packages):
        for copyright, text in licence_files(key, packages[key]):
            _, copyrights, users = groups.setdefault(" ".join(text.split()), (text, set(), set()))
            copyrights.update(filter(None, copyright.splitlines()))
            users.add(key[0])

    out = ["", "### Licence texts", ""]
    out += ["The licence texts of the crates and packages above. Packages with the same"]
    out += ["text share one copy, preceded by all of their copyright lines.", ""]
    ordered = sorted(groups.values(), key=lambda g: (-len(g[2]), g[0]))
    for number, (text, copyrights, users) in enumerate(ordered, 1):
        flat = " ".join(re.sub(r"(?m)^[\s/#*]+", "", text).split())
        names = sorted((flat.find(words), spdx) for spdx, words in KNOWN_TEXTS.items() if words in flat)
        fence = "````" if "```" in text else "```"
        out += [f"#### {number}. {', '.join(n for _, n in names) or 'Other'}", ""]
        out += [f"Used by: {', '.join(sorted(users, key=str.lower))}.", "", fence]
        out += sorted(copyrights, key=str.lower) + ([""] if copyrights else [])
        out += [text, fence, ""]
    return out[:-1]


def render() -> str:
    crates = rust_crates()
    shipped_in: dict[Key, set[str]] = defaultdict(set)
    for binary, targets in BINARIES.items():
        for key in shipped_crates(binary, targets):
            if key in crates:  # skips our own workspace crates
                shipped_in[key].add(binary)

    npm_all = npm_packages(prod=False)
    npm_shipped = npm_packages(prod=True)
    npm_shipped |= {k: v for k, v in npm_all.items() if k[0] in NPM_BUILD_OUTPUT}

    # One row per name: two versions of a crate share it unless their licences differ.
    rust_rows = {(k[0], crates[k][0], ", ".join(sorted(shipped_in[k]))) for k in shipped_in}
    out = [BEGIN, "", "### Rust crates in shipped binaries", ""]
    out += ["| Crate | Licence | Shipped in |", "|---|---|---|"]
    out += [f"| {name} | {licence} | {binaries} |" for name, licence, binaries in sorted(rust_rows)]

    npm_rows = {(k[0], v[0], NPM_BUILD_OUTPUT.get(k[0], "")) for k, v in npm_shipped.items()}
    out += ["", "### npm packages in the sidebar bundle", ""]
    out += ["| Package | Licence | Note |", "|---|---|---|"]
    out += [f"| {name} | {licence} | {note} |" for name, licence, note in sorted(npm_rows)]

    shipped = {key: crates[key] for key in shipped_in} | npm_shipped
    out += render_texts(shipped)
    out += ["", END]
    return "\n".join(out)


def main() -> int:
    text = NOTICES.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    updated = text[:start] + render() + text[end:]
    if "--check" in sys.argv[1:]:
        if updated != text:
            print(f"{NOTICES.name} is out of date: run python3 tools/third-party-notices.py")
            return 1
        return 0
    NOTICES.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
